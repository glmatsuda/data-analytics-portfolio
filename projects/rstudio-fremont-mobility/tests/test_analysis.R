s <- readRDS("results/validation-state.rds")
stopifnot(max(s$train$date)<min(s$test$date))
stopifnot(all(s$train$year<=2023),all(s$test$year==2024),all(s$test$complete_day==1))
stopifnot(!anyDuplicated(s$test$date),all(is.finite(s$test$model_prediction)),all(s$test$model_prediction>=0))
hold <- subset(s$metrics,population=="2024 holdout")
stopifnot(all(hold$n==nrow(s$test)))
stopifnot(abs(hold$MAE[1]-mean(abs(s$test$crossings-s$test$model_prediction)))<1e-9)
stopifnot(abs(hold$MAE[2]-mean(abs(s$test$crossings-s$test$baseline_prediction)))<1e-9)
cat("Mobility model checks passed: temporal separation, complete-day population, unique dates, finite predictions, matched baseline population, independent MAE.\n")
